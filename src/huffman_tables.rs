// Table 3-B.7 — Huffman codes for Layer III.
//
// Transcribed by hand from ISO/IEC 11172-3:1993 Annex B, Table 3-B.7
// (PDF pages rendered with pdftoppm: tables 0–10 on p.54–55, 11–13 on
// p.56–57, 15 on p.57–58, 16 + the 17–23 linbits derivations on
// p.59–60, 24 + the 25–31 linbits derivations on p.60–61).
//
// Each table is a square `(x, y)` codebook stored row-major as
// `[x * xlen + y]`. `e(len, code)` is `(hlen, hcod)`; `e(0, 0)` marks
// an unused corner. Tables 4 and 14 are "not used" per the spec.
//
// Codebooks 16..=23 share table 16's `(x, y)` codes with differing
// `linbits`; codebooks 25..=31 share table 24's codes likewise. We
// reference one canonical entry slice and vary only `linbits`.

// b(x,y) helper not needed: we build flat arrays directly.

// ---------------------------------------------------------------------
// Quad table A (Table 3-B.7-A): indexed by the 4-bit vwxy pattern,
// stored as (hlen, hcod). count1 quad table B is the trivial code and
// is handled inline in huffman.rs.
// ---------------------------------------------------------------------
const QUAD_A: [(u8, u16); 16] = [
    (1, 0b1),       // 0000
    (4, 0b0101),    // 0001
    (4, 0b0100),    // 0010
    (5, 0b00101),   // 0011
    (4, 0b0110),    // 0100
    (6, 0b000101),  // 0101
    (5, 0b00100),   // 0110
    (6, 0b000100),  // 0111
    (4, 0b0111),    // 1000
    (5, 0b00011),   // 1001
    (5, 0b00110),   // 1010
    (6, 0b000000),  // 1011
    (5, 0b00111),   // 1100
    (6, 0b000010),  // 1101
    (6, 0b000011),  // 1110
    (6, 0b000001),  // 1111
];

